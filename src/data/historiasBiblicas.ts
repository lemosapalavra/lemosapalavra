/** Duas histórias por dia, alternando ao longo do ano. */
export function historiasDoDia(date = new Date()): HistoriaBiblica[] {
  const start = new Date(date.getFullYear(), 0, 0).getTime();
  const day = Math.floor((date.getTime() - start) / 86400000);
  const total = historias.length;
  const a = (day * 2) % total;
  const b = (day * 2 + 1) % total;
  return [historias[a], historias[b]];
}
